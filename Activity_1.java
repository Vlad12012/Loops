public class Activity_1 {
    public static void main(String[] args) {
        for (int i = 1; i<=100; i++){
            System.out.println("The value of i is: " + i);
        }
        
        System.out.println("---------------------------------");
        
        int a = 100;

        while (a>=1){
            System.out.println("The value of a is: " + a);
            a--;
        }
    }
}
